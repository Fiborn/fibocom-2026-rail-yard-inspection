    public AgentAdviceResponse advice(AgentAdviceRequest request) {
        double confidence = request.getConfidence() == null ? 0 : request.getConfidence();
        String targetClass = String.valueOf(request.getTargetClass());
        AlarmAdvice alarmAdvice = adviceMap.getOrDefault(targetClass, fallbackAdvice(request));
        int levelIndex = severityIndex(confidence);
        String severity = switch (levelIndex) {
            case 2 -> "三级（高危）";
            case 1 -> "二级（中等）";
            default -> "一级（轻微）";
        };
        String advice = randomAdvice(alarmAdvice.advices()[levelIndex]);
        return new AgentAdviceResponse(targetClass, alarmAdvice.label(), confidence, severity, advice);
    }

    private int severityIndex(double confidence) {
        double percent = confidence <= 1 ? confidence * 100 : confidence;
        if (percent >= 90) return 2;
        if (percent >= 80) return 1;
        return 0;
    }

    private String randomAdvice(String[] advices) {
        int index = ThreadLocalRandom.current().nextInt(advices.length);
        return advices[index];
    }

